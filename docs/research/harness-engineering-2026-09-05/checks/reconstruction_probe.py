#!/usr/bin/env python3
"""Reconstruct the documented pure-renderer probe; this is not a kernel test.

The original probe was an inline invocation. This saved version reads its retained
synthetic inputs and results, checks the pinned source and baseline output bytes,
and writes only to a TemporaryDirectory, removed on exit. No production module is
imported. Only the existing _bullets and render_views definitions are executed.
"""

import ast
import hashlib
import json
from pathlib import Path
from tempfile import TemporaryDirectory
from typing import Any


SOURCE_SHA256 = "70ba222a527c284a9dab9151fcb27f035f030a16c401939a0cada168de8bc729"
OUTPUTS = {
    "progress.md", "reviews/README.md", "views/report-index.md",
    "views/submission-index.md", "memory/README.md", "cleanup.generated.md",
}
FIXTURES = Path(__file__).resolve().parent / "reconstruction"


def main() -> None:
    source_path = Path(__file__).resolve().parents[4] / "tools/engagement_views.py"
    source = source_path.read_bytes()
    if hashlib.sha256(source).hexdigest() != SOURCE_SHA256:
        raise RuntimeError("Renderer source differs from the inspected research revision")
    tree = ast.parse(source, filename=str(source_path))
    selected = [node for node in tree.body if isinstance(node, ast.FunctionDef)
                and node.name in {"_bullets", "render_views"}]
    if [node.name for node in selected] != ["_bullets", "render_views"]:
        raise RuntimeError("Expected exactly the two inspected pure functions")
    namespace = {
        "Any": Any,
        "SENTINEL": "<!-- GENERATED by tools/run-engagement.py; edit authoritative records, not this file. -->",
    }
    exec(compile(ast.Module(body=selected, type_ignores=[]), str(source_path), "exec"), namespace)
    render = namespace["render_views"]
    original = json.loads((FIXTURES / "results.json").read_text())
    if original["source_sha256"] != SOURCE_SHA256 or set(original["output_files"]) != OUTPUTS:
        raise RuntimeError("Original result metadata does not match this probe")

    with TemporaryDirectory(prefix="reconstruction-probe-") as temporary:
        rendered = {}
        for name in ["snapshot", *original["checks"]]:
            snapshot = json.loads((FIXTURES / f"{name}.json").read_text())
            outputs = render(snapshot)
            if set(outputs) != OUTPUTS:
                raise RuntimeError(f"Unexpected output set for {name}")
            for relative, data in outputs.items():
                destination = Path(temporary) / name / relative
                destination.parent.mkdir(parents=True, exist_ok=True)
                destination.write_bytes(data)
            rendered[name] = outputs
        baseline = rendered["snapshot"]
        if any(data != (FIXTURES / "rendered" / relative).read_bytes()
               for relative, data in baseline.items()):
            raise RuntimeError("Baseline differs from the original retained output bytes")
        checks = {}
        for name, expected in original["checks"].items():
            identical = {path: rendered[name][path] == baseline[path] for path in sorted(OUTPUTS)}
            if all(identical.values()) != expected["all_six_views_identical"]:
                raise RuntimeError(f"Recorded comparison did not reproduce: {name}")
            checks[name] = {"all_six_views_identical": all(identical.values()),
                            "identical_by_output": identical}
        print(json.dumps({"source_sha256": SOURCE_SHA256, "baseline_bytes_match": True,
                          "checks": checks, "temporary_outputs_removed_on_exit": True}, indent=2))


if __name__ == "__main__":
    main()
