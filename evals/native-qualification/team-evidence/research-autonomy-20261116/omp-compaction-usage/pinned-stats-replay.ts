import { createHash } from 'node:crypto';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
const [sdk, output] = process.argv.slice(2);
if (!sdk || !output) throw new Error('Pass the pinned pi-coding-agent package directory and output JSON path.');
const source=path.resolve(sdk,'src/session/session-stats.ts');
const bytes=new Uint8Array(await Bun.file(source).arrayBuffer());
const sourceHash=createHash('sha256').update(bytes).digest('hex');
if ((await Bun.file(path.resolve(sdk,'package.json')).json()).version!=='18.20.0' || sourceHash!=='3304c091832469ce191d0c767d675c4963d3555a6249e1374dfbccc4bc27d7d9') throw new Error('Pinned stats source mismatch.');
const { SessionStatsTracker } = await import(pathToFileURL(source).href);
const assistant=(n:number)=>({role:'assistant',content:[],usage:{input:n,output:n,reasoningTokens:0,cacheRead:n,cacheWrite:0,totalTokens:3*n,cost:{total:n/100}}});
const state={messages:[assistant(100)]};
const tracker=new SessionStatsTracker({agent:{state},sessionManager:{getBranchView:()=>[],getSessionFile:()=>undefined},sessionId:()=> 'owned-stats-session'} as any);
tracker.getContextUsage=()=>undefined;
const snapshot=()=>{const {tokens,cost}=tracker.getSessionStats();return {tokens,cost};};
const before=snapshot();
state.messages=[assistant(100),assistant(10)]; const normal=snapshot();
state.messages=[{role:'user',content:'Owned compacted context.'} as any,assistant(5)]; const compacted=snapshot();
state.messages=[{role:'user',content:'Owned compacted context.'} as any,assistant(120)]; const compactedPositive=snapshot();
const result={kind:'pinned-omp-active-window-stats-replay-v1',version:'18.20.0',source_sha256:sourceHash,before,normal,compacted,compactedPositive};
await Bun.write(output,JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result));
if(!(compacted.tokens.total<before.tokens.total && compactedPositive.tokens.total>before.tokens.total))process.exit(1);
